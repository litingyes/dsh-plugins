/**
 * Build the browser half into `client.js`.
 *
 * The delivered artifact must be one file in the Harness module-loader format:
 * a `window.__ModuleLoader__.load({ id, factory(require) })` registration whose
 * factory returns `{ name, inject, apply }`. esbuild produces the body; this
 * script adds the envelope.
 *
 * Only React, React DOM and the JSX runtime may stay external: they are leaves
 * of the Web UI's shared module table. Everything else is compiled in, and a new
 * bare `require` in the output fails the build instead of shipping a bundle that
 * cannot resolve.
 *
 * Usage:
 *   `npm run build`     rewrite client.js
 *   `node scripts/build-client.mjs --check`
 *                      build in memory and fail when the committed client.js no
 *                      longer matches the sources or the manifest version. The
 *                      banner carries `<name>@<version>`, so a version bump
 *                      without a rebuild is exactly the drift this catches.
 */

import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { gzipSync } from 'node:zlib'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)))

/** Modules the Web UI's shared module table supplies at runtime. */
const PLATFORM_MODULES = ['react', 'react-dom', 'react/jsx-runtime']

/** `--check` compares instead of writing, so CI and `npm run check` can assert freshness. */
const checkOnly = process.argv.includes('--check')

const manifest = JSON.parse(await readFile(path.join(packageRoot, 'package.json'), 'utf8'))

const result = await build({
  entryPoints: [path.join(packageRoot, 'src/client/index.jsx')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2020'],
  jsx: 'transform',
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'warning',
  external: PLATFORM_MODULES,
  define: { 'process.env.NODE_ENV': '"production"' },
  metafile: true,
})

const body = result.outputFiles[0].text

const required = new Set()
for (const match of body.matchAll(/require\(\s*["']([^"']+)["']\s*\)/gu)) required.add(match[1])
const unexpected = [...required].filter(name => !PLATFORM_MODULES.includes(name))
if (unexpected.length > 0) {
  throw new Error(
    `client bundle has unexpected external module(s): ${unexpected.join(', ')}\n` +
      `Platform modules are ${PLATFORM_MODULES.join(', ')}. ` +
      'A third-party module must be bundled, not externalized: dsh.client.external only ' +
      're-exports modules another row already supplies.',
  )
}

const inline = [
  '/*',
  ` * ${manifest.name}@${manifest.version} — browser half.`,
  ' *',
  ' * Generated by scripts/build-client.mjs from src/client/. Do not edit this file:',
  ' * edit the sources and run `npm run build`.',
  ' *',
  ' * React, React DOM and the JSX runtime are resolved from the Harness Web UI',
  ' * shared module table; everything else is bundled.',
  ' */',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(manifest.name)},`,
  '  factory(require) {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
].join('\n')

const tail = [
  '',
  '    return {',
  '      name: module.exports.name,',
  '      inject: module.exports.inject,',
  '      apply: module.exports.apply,',
  '    };',
  '  },',
  '});',
  '',
].join('\n')

const output = `${inline}\n${body}\n${tail}`
const outFile = path.join(packageRoot, 'client.js')

const bytes = Buffer.byteLength(output, 'utf8')
const gzipped = gzipSync(Buffer.from(output, 'utf8')).length
const inputs = Object.keys(result.metafile.inputs).length
const summary =
  `${(bytes / 1024).toFixed(1)} KiB raw, ${(gzipped / 1024).toFixed(1)} KiB gzip, ` +
  `${inputs} inputs, externals: ${[...required].join(', ') || 'none'}`

if (checkOnly) {
  const committed = await readFile(outFile, 'utf8').catch(() => null)
  if (committed === null) {
    console.error('client.js is missing; run `npm run build`')
    process.exit(1)
  }
  if (committed !== output) {
    console.error(
      'client.js is stale; run `npm run build` and commit the result\n' +
        '  (the banner carries the manifest version, so a version bump without a rebuild also fails here)',
    )
    process.exit(1)
  }
  console.log(`build-client: client.js is fresh (${summary})`)
} else {
  await writeFile(outFile, output)
  console.log(`build-client: wrote client.js (${summary})`)
}
